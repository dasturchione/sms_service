import { BaseCommand, args, flags } from '@adonisjs/core/ace'
import type { CommandOptions } from '@adonisjs/core/types/ace'
import { randomBytes } from 'node:crypto'
import StaffService from '#services/admin/staff_service'
import User from '#models/user'
import { UserRole } from '#enums/tenant'

/**
 * Creates a platform operator account from the server.
 *
 * This exists because there is no self-signup: an account here can approve
 * gateways and mint credentials that spend money on the platform's SIMs, so it
 * is not something a stranger who found the URL should be able to create.
 *
 * That leaves two jobs for this command. It bootstraps the very first operator,
 * who then invites the rest through the back office, and it is the way back in
 * when every account is locked out — which is why it deliberately requires
 * shell access to the server rather than a password anyone can type into a
 * form.
 */
export default class CreateStaff extends BaseCommand {
  static commandName = 'staff:create'
  static description = 'Create a platform operator account (bootstrap or recovery)'
  static options: CommandOptions = { startApp: true }

  @args.string({ description: 'Email address used to sign in' })
  declare email: string

  @flags.string({ description: 'Full name shown in the back office' })
  declare name: string

  @flags.string({
    description: 'Password. Omit to have a strong one generated and printed once.',
  })
  declare password: string

  @flags.string({
    description: `Role: ${UserRole.OWNER} or ${UserRole.ADMIN}`,
    /**
     * Widened to `string` so the flag accepts whatever was typed and this
     * command can reject it with an explanation, rather than the decorator
     * narrowing the property to the default's literal type.
     */
    default: UserRole.ADMIN as string,
  })
  declare role: string

  async run() {
    if (!this.isAdministrativeRole(this.role)) {
      this.logger.error(
        `Role must be "${UserRole.OWNER}" or "${UserRole.ADMIN}". ` +
          'Only those two can reach the back office; anything else would sign in and then be refused.'
      )
      this.exitCode = 1
      return
    }

    if (this.password && this.password.length < 12) {
      /**
       * Stricter than the back office form on purpose. A password typed on a
       * command line also lands in shell history, so a weak one here is
       * exposed twice over.
       */
      this.logger.error('A password given on the command line must be at least 12 characters')
      this.exitCode = 1
      return
    }

    /**
     * Generated by default so the common path cannot produce a weak password,
     * and so nothing secret has to be typed where it would be recorded.
     */
    const generated = !this.password
    const password = this.password || randomBytes(18).toString('base64url')

    const existingStaff = await User.query().whereNull('tenant_id').count('* as total')
    const isFirst = Number(existingStaff[0].$extras.total) === 0

    let user: User
    try {
      user = await StaffService.create({
        email: this.email.trim().toLowerCase(),
        password,
        fullName: this.name ?? null,
        role: this.role as UserRole,
      })
    } catch (error) {
      this.logger.error(error instanceof Error ? error.message : String(error))
      this.exitCode = 1
      return
    }

    this.logger.success(`Operator "${user.email}" created`)

    const table = this.ui.table().head(['Field', 'Value']).row(['Email', user.email])

    if (generated) table.row(['Password', password])

    table
      .row(['Role', user.role])
      .row(['UID', user.uid ?? '—'])
      .render()

    if (generated) {
      this.logger.warning('The password is not stored in readable form and cannot be shown again.')
    }

    if (isFirst) {
      this.logger.info(
        'This is the first operator account. Sign in at POST /api/v1/auth/login, ' +
          'then invite the rest through the back office at POST /api/v1/admin/staff.'
      )
    }
  }

  private isAdministrativeRole(role: string): boolean {
    return role === UserRole.OWNER || role === UserRole.ADMIN
  }
}
